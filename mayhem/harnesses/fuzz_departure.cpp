// set_departure_functions (JSON or REFPROP HMX.BNC text) and set_interaction_parameters
// (binary-interaction JSON), then a Methane/Ethane mixture evaluation that uses the loaded data.
//
// Per-input isolation. With OVERWRITE_DEPARTURE_FUNCTION / OVERWRITE_BINARY_INTERACTION on, an input
// can rewrite shipped records, and nothing in CoolProp removes or resets them. The evaluation reads
// exactly two things an input can change: the Methane/Ethane binary-pair record (CAS 74-82-8 &
// 74-84-0) and, when its F != 0, the departure function that record names. So:
//  * after every input, the shipped departure-function library (every shipped Name and alias) and
//    the shipped Methane/Ethane record are re-loaded from the same embedded JSON CoolProp loads its
//    defaults from (include/mixture_*_JSON.h, generated by the CoolProp build); the evaluation of
//    the next input therefore starts from the shipped data plus only what that input sets;
//  * records an input adds under NEW names/pairs cannot be removed through any API. The only way
//    one could reach a later evaluation is a later input's Methane/Ethane record naming it, so the
//    evaluation runs only when the in-force departure function is a shipped name or one this input
//    itself defines (JSON Name/aliases, or the HMX.BNC model names, parsed by CoolProp's own
//    parse_HMX_BNC).
#include "common.h"
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <iterator>
#include <set>
#include <string_view>
#include <nlohmann/json.hpp>
#include "CoolProp/CoolPropLib.h"
#include "CoolProp/DataStructures.h"
#include "mixture_departure_functions_JSON.h"  // shipped departure functions (CoolProp build output)
#include "mixture_binary_pairs_JSON.h"         // shipped binary pairs (CoolProp build output)

namespace CoolProp {
// Same declarations as src/Backends/Helmholtz/MixtureParameters.h (not a public header; including
// it pulls in the whole HEOS backend headers): defined with external linkage in MixtureParameters.cpp.
struct REFPROP_binary_element {
    std::string CAS1, CAS2, model;
    double betaT, gammaT, betaV, gammaV, Fij;
    std::vector<std::string> comments;
};
struct REFPROP_departure_function {
    short Npower = 0, Nspecial = 0, Nterms_power = 0, Nterms_special = 0;
    std::string model;
    std::vector<double> a, t, d, e, eta, epsilon, beta, gamma;
    std::vector<std::string> comments;
};
void set_departure_functions(const std::string& string_data);  // MixtureParameters.h
void parse_HMX_BNC(const std::string& s, std::vector<REFPROP_binary_element>& BIP, std::vector<REFPROP_departure_function>& functions);
}  // namespace CoolProp

static const char* kCH4 = "74-82-8";
static const char* kC2H6 = "74-84-0";
static std::string g_dep_defaults;   // shipped departure-function JSON
static std::string g_bip_defaults;   // shipped Methane/Ethane record(s), JSON array
static std::set<std::string> g_shipped_names;

static std::string without_nul(std::string_view v) {
    while (!v.empty() && v.back() == '\0') v.remove_suffix(1);
    return std::string(v);
}

static void add_names(const nlohmann::json& doc, std::set<std::string>& out) {
    if (!doc.is_array()) return;
    for (const auto& el : doc) {
        if (!el.is_object()) continue;
        if (el.contains("Name") && el["Name"].is_string()) out.insert(el["Name"].get<std::string>());
        if (el.contains("aliases") && el["aliases"].is_array())
            for (const auto& a : el["aliases"])
                if (a.is_string()) out.insert(a.get<std::string>());
    }
}

static void restore_defaults() {
    try {
        CoolProp::set_departure_functions(g_dep_defaults);
        CoolProp::set_interaction_parameters(g_bip_defaults);
    } catch (const std::exception& e) {
        std::fprintf(stderr, "fuzz_departure: restoring the shipped mixture data failed: %s\n", e.what());
        std::abort();
    }
}

extern "C" int LLVMFuzzerInitialize(int*, char***) {
    cp_fuzz_warmup();
    g_dep_defaults = without_nul(mixture_departure_functions_JSON);
    add_names(nlohmann::json::parse(g_dep_defaults), g_shipped_names);
    nlohmann::json me = nlohmann::json::array();
    for (const auto& el : nlohmann::json::parse(without_nul(mixture_binary_pairs_JSON))) {
        const std::string a = el.value("CAS1", ""), b = el.value("CAS2", "");
        if ((a == kCH4 && b == kC2H6) || (a == kC2H6 && b == kCH4)) me.push_back(el);  // last one is in force
    }
    if (me.empty()) { std::fprintf(stderr, "fuzz_departure: no shipped Methane/Ethane record\n"); std::abort(); }
    g_bip_defaults = me.dump();
    // Reloading collapses a multi-model pair to its in-force record; do it once here too so every
    // input starts from the very state restore_defaults() leaves behind.
    restore_defaults();
    return 0;
}

extern "C" int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size) {
    std::string s(reinterpret_cast<const char*>(data), size);
    std::set<std::string> own = g_shipped_names;
    if (s.find("#MXM") != std::string::npos) {
        std::vector<CoolProp::REFPROP_binary_element> bip;
        std::vector<CoolProp::REFPROP_departure_function> fns;
        try {
            CoolProp::parse_HMX_BNC(s, bip, fns);
            for (const auto& f : fns) own.insert(f.model);
        } catch (...) {
        }
    } else {
        add_names(nlohmann::json::parse(s, nullptr, /*allow_exceptions=*/false), own);
    }
    long err = 0;
    char msg[512];
    ::set_departure_functions(s.c_str(), &err, msg, sizeof msg);
    try {
        CoolProp::set_interaction_parameters(s);
    } catch (...) {
    }
    bool eval = true;
    try {
        // The mixture code reads the departure function unless |F| < DBL_EPSILON; F is read back
        // printed with %0.16g, so gate on any non-zero (or NaN) value, the conservative side.
        const double F = std::strtod(CoolProp::get_mixture_binary_pair_data(kCH4, kC2H6, "F").c_str(), nullptr);
        if (!(F == 0))
            eval = own.count(CoolProp::get_mixture_binary_pair_data(kCH4, kC2H6, "function")) > 0;
    } catch (...) {
        // No usable F/function: the mixture code reports that itself; nothing stale can be read.
    }
    if (eval) {
        (void)CoolProp::PropsSI("D", "T", 250, "P", 1e6, "HEOS::Methane[0.5]&Ethane[0.5]");
        (void)CoolProp::PropsSI("P", "T", 200, "Q", 0, "HEOS::Methane[0.5]&Ethane[0.5]");
    }
    restore_defaults();
    return 0;
}
